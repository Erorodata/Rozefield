"""Generate backup_tool/backup_queries.h: every read-only look-up the backup window sends after login.

Built from the game's own rules, not one player's capture: the request list comes from the protocol, and the
ids it walks (achievement groups, characters, scenes, areas, shops, recruit banners, ...) come from the game tables,
so it covers any account. Bodies for archive keys come from the official client's own requests.
    py tools/gen_backup_queries.py
"""
import json, os, sys
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)
from ofproto import from_dict, NAME2ID, pool  # noqa: E402


def rows(f, s):
    d = json.load(open(os.path.join(HERE, 'data', f), encoding='utf-8'))[s]
    return d['datas'] if isinstance(d, dict) else d


def enum(name):
    return [v.name for v in pool.FindEnumTypeByName('pb.' + name).values if not v.name.endswith('_NONE')]


# GetArchiveInfoReq keys seen from the official client (tutorial and settings flags; same for every player)
ARCHIVE_KEYS = json.load(open(os.path.join(HERE, 'tools', 'archive_keys.json'), encoding='utf-8'))


def build():
    Q = []
    add = lambda n, b=None: Q.append((n, b or {}))
    # account summary first, then everything shown on a screen
    for n in ('PlayerMainDataReq', 'PlayerAbilityListReq', 'PosterIllustrationListReq', 'WorldLevelAchieveListReq',
              'SupplyBoxInfoReq', 'AbilityBadgeListReq', 'GachaListReq', 'GetAllCharacterEquipReq', 'SceneProcessListReq',
              'GetMailsReq', 'GetGardenInfoReq', 'GardenFurnitureSchemeReq', 'GardenLikeRecordReq', 'GetCollectItemIdsReq',
              'GetAchieveGroupListReq', 'ManualListReq', 'TreasureIllustrationInfoReq', 'PlayerEnergyInfoReq', 'ExploreInitReq',
              'FriendIntervalInitReq', 'SelfIntervalInitReq', 'AbyssInfoReq', 'UnlockHeadListReq', 'MPPlayRoomRewardInfoReq',
              'ChallengeFriendRankReq', 'WishListByFriendIdReq'):
        add(n)
    for n in ('GetWeaponReq', 'GetArmorReq', 'GetPosterReq', 'GetPetReq'):
        add(n, {'endIndex': 100000})
    for t in enum('FriendListType'):
        add('FriendReq', {'type': t})
    for t in enum('LifeType'):
        for n in ('GetLifeInfoReq', 'GetLifeSkillReq', 'GetLifeAchieveReq', 'GetOneTypeLifePictorialBookCountReq'):
            add(n, {'life_type': t})
    for r in rows('achievequest.json', 'AchieveQuestGroup'):
        add('GetAchieveOneGroupReq', {'groupId': r['ID']})
    for r in rows('character.json', 'Character'):
        add('GetCharacterAchievementListReq', {'characterId': r['ID']})
    areas = [r['ID'] for r in rows('area.json', 'AreaData')]
    area_ids = sorted({g['AreaID'] for r in rows('area.json', 'AreaData') for g in r.get('AreaDataGroup', []) if g.get('AreaID')})
    for a in area_ids:   # the exploration areas inside each map (Global Search "Exploration n/4")
        add('AreaAchieveListReq', {'areaId': a})
    for sid in sorted(set(areas) | {9999, 1000}):
        add('GetCollectMoonInfoReq', {'sceneId': sid})
    for i in range(1, 11):
        add('GardenSchemeFurnitureListReq', {'scheme_id': i})
    for r in rows('gacha.json', 'Info'):
        add('GachaRecordReq', {'gachaId': r['ID'], 'page': 1})
    for r in rows('shop.json', 'Info'):
        add('ShopInfoReq', {'shopId': r['ID']})
    for r in rows('bossrush.json', 'BossRushSeason'):
        add('BossRushInfoReq', {'season_id': r['ID']})
    for a in sorted({r['ActivityID'] for r in rows('restaurantgame.json', 'RestaurantDungeon')}):
        add('RestaurantGameInfoReq', {'activity_id': a})
    keys = set(ARCHIVE_KEYS)   # tutorial / settings flags (their names live in the client's UI, not the tables)
    for a in areas:   # per-area flags built by the client as Scene<area>ChallengeType / RiddleType
        keys |= {'Scene%dChallengeType' % a, 'Scene%dRiddleType' % a}
    for k in sorted(keys):
        add('GetArchiveInfoReq', {'key': k})
    return Q


def main():
    Q = build()
    out = ['/* generated by tools/gen_backup_queries.py from the protocol and the game tables: read-only look-ups */',
           'struct query { int msg_id; int len; const unsigned char *body; };']
    for i, (n, b) in enumerate(Q):
        raw = from_dict(n, b).SerializeToString()
        out.append('static const unsigned char Q%d[] = {%s};  /* %s %s */' % (i, ','.join(map(str, raw)) or '0', n,
                   json.dumps(b, ensure_ascii=True).replace('*/', '')))
    out.append('static const struct query QUERIES[] = {')
    for i, (n, b) in enumerate(Q):
        out.append('    {%d, %d, Q%d},' % (NAME2ID[n], len(from_dict(n, b).SerializeToString()), i))
    out.append('};\n#define NQUERY ((int)(sizeof QUERIES / sizeof QUERIES[0]))')
    open(os.path.join(HERE, 'backup_tool', 'backup_queries.h'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print(len(Q), 'look-ups')


if __name__ == '__main__':
    main()
